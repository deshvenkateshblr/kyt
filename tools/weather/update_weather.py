#!/usr/bin/env python3
"""Build data/weather.js: monthly average high, low and rainfall for every city in data/cities.js.

Source: NASA POWER climatology (free, no account or key, "no restrictions on the use" of the data; please
credit NASA POWER). Standard library only, so there is nothing to install.

    python tools/weather/update_weather.py              # fill in cities that have no weather yet
    python tools/weather/update_weather.py --refresh    # fetch every city again (new NASA release)
    python tools/weather/update_weather.py --cities leh,manali --refresh
    python tools/weather/update_weather.py --dry-run    # show what would change, write nothing
    python tools/weather/update_weather.py --limit 5    # a quick trial on the first 5 cities

What it writes, one line per city so git diffs stay readable (hi and lo are mean DAILY highs and lows, from NASA's
T2M_MAX_AVG and T2M_MIN_AVG, not the T2M_MAX and T2M_MIN extremes):

    "agra": {"hi": [12 monthly mean daily highs, deg C], "lo": [12 mean daily lows, deg C],
             "rain": [12 monthly totals, mm], "src": "nasa-power"}

Hand corrections: put a COMPLETE entry (hi, lo and rain, 12 numbers each) in data/weather-overrides.json, for
example from the IMD normals for a hill city. It wins over NASA, the city is not fetched, and the script keeps
it on every later run:

    {"leh": {"hi": [...], "lo": [...], "rain": [...], "source": "IMD normals 1991-2020"}}

Know the limits: NASA's grid cell is about 55 km (0.5 x 0.625 degrees), so it smooths mountains and coastlines.
Hill cities are listed at the end of every run; spot-check them and override where they look wrong.

Exit status is 1 if any city failed, so a scheduled run can be noticed. Raw API answers are cached in
tools/weather/.cache (not committed), so a run that dies halfway resumes without asking NASA again.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
API = "https://power.larc.nasa.gov/api/temporal/climatology/point"
# Mean daily high and low (C) and rain (mm per day). NOT T2M_MAX / T2M_MIN: those are the single hottest and coldest
# hourly reading in the whole period, which gave Delhi a 48 C "high" in June and Leh a -39 C "low".
HI_PARAM, LO_PARAM, RAIN_PARAM = "T2M_MAX_AVG", "T2M_MIN_AVG", "PRECTOTCORR"
# Climates anyone can check, as (month index, lowest, highest) of the mean daily value. A run whose temperatures miss
# these is refused rather than written, because that means the wrong parameter or a changed API, not a freak climate.
ANCHORS = {
    "delhi":   {"hi": [(0, 17, 25), (4, 36, 44)], "lo": [(0, 3, 11)]},
    "mumbai":  {"hi": [(0, 28, 34)]},
    "chennai": {"hi": [(0, 26, 32)]},
}
COMMUNITY = "AG"
MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]
DAYS = [31, 28.25, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
SOURCE_NAME = "NASA POWER climatology"
DEFAULT_PERIOD = "2001-2020"                     # as stated on NASA's pages; the script records it, it does not check it
HEADER = (
    "// Generated by tools/weather/update_weather.py from NASA POWER climatology. Do not edit by hand:\n"
    "// corrections go in data/weather-overrides.json and survive every run.\n"
    "// hi / lo: mean daily high / low per month in deg C (Jan to Dec). rain: mean monthly total in mm.\n"
)


# ── Reading the repo's data ───────────────────────────────────────────────────────────────────────────────────

def _json_after(text: str, marker: str):
    """The JSON value that follows `marker` in a JS file such as `window.KYT_CITIES = [ ... ];`."""
    at = text.index(marker) + len(marker)
    start = min(i for i in (text.find("[", at), text.find("{", at)) if i != -1)
    value, _ = json.JSONDecoder().raw_decode(text[start:])
    return value


def load_cities(path: Path) -> list[dict]:
    cities = _json_after(path.read_text(encoding="utf-8"), "window.KYT_CITIES")
    out = []
    for c in cities:
        lat, lng = c.get("lat"), c.get("lng")
        if not isinstance(lat, (int, float)) or not isinstance(lng, (int, float)):
            raise SystemExit(f"{c.get('id')} has no lat/lng in {path}")
        out.append({"id": c["id"], "name": c.get("name", c["id"]), "lat": lat, "lng": lng, "setting": c.get("setting")})
    return out


def load_weather(path: Path) -> dict:
    if not path.exists():
        return {"meta": {}, "cities": {}}
    data = _json_after(path.read_text(encoding="utf-8"), "window.KYT_WEATHER")
    data.setdefault("meta", {})
    data.setdefault("cities", {})
    return data


def load_overrides(path: Path) -> dict:
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise SystemExit(f"{path} must be a JSON object keyed by city id")
    return data


# ── NASA POWER ────────────────────────────────────────────────────────────────────────────────────────────────

def request_url(lat: float, lng: float, community: str = COMMUNITY, names=(HI_PARAM, LO_PARAM, RAIN_PARAM)) -> str:
    q = {"parameters": ",".join(names), "community": community, "longitude": f"{lng:.4f}", "latitude": f"{lat:.4f}", "format": "JSON"}
    return API + "?" + urllib.parse.urlencode(q, safe=",")


def _api_message(e: urllib.error.HTTPError) -> str:
    """NASA explains a rejected request in the body; show it, trimmed, so a wrong parameter name is obvious."""
    try:
        body = json.loads(e.read().decode("utf-8", "replace"))
        msgs = body.get("messages") or body.get("message") or body
        text = "; ".join(map(str, msgs)) if isinstance(msgs, list) else str(msgs)
    except Exception:
        return ""
    return (": " + text[:300]) if text else ""


def fetch_json(url: str, retries: int = 4, timeout: float = 60, sleep=time.sleep) -> dict:
    """GET a URL and decode the JSON. Retries timeouts, 429 and 5xx with growing waits; other errors fail at once."""
    wait = 2.0
    for attempt in range(retries + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "KYT-weather-updater/1.0", "Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            if e.code not in (429, 500, 502, 503, 504) or attempt == retries:
                raise RuntimeError(f"HTTP {e.code} from NASA POWER{_api_message(e)}") from None
            retry_after = e.headers.get("Retry-After") if e.headers else None
            sleep(float(retry_after) if retry_after and retry_after.isdigit() else wait)
        except (urllib.error.URLError, TimeoutError, ConnectionError) as e:
            if attempt == retries:
                raise RuntimeError(f"could not reach NASA POWER ({getattr(e, 'reason', e)})") from None
            sleep(wait)
        wait *= 2
    raise RuntimeError("unreachable")


def parse_response(data: dict, names=(HI_PARAM, LO_PARAM, RAIN_PARAM)) -> dict:
    """NASA's answer to {hi, lo, rain} lists. Raises ValueError, naming what is wrong, on anything unexpected."""
    try:
        params = data["properties"]["parameter"]
        blocks = {"hi": params[names[0]], "lo": params[names[1]], "rain": params[names[2]]}
    except (KeyError, TypeError) as e:
        raise ValueError(f"unexpected response shape (missing {e}); is the API format still properties.parameter?") from None
    fill = (data.get("header") or {}).get("fill_value", -999)

    def months(block, name):
        vals = []
        for m in MONTHS:
            v = block.get(m) if isinstance(block, dict) else None
            if isinstance(v, bool) or not isinstance(v, (int, float)) or v == fill or v <= -990:
                raise ValueError(f"{name} {m} is missing or a fill value ({v!r})")
            vals.append(float(v))
        return vals

    hi, lo, per_day = months(blocks["hi"], names[0]), months(blocks["lo"], names[1]), months(blocks["rain"], names[2])
    return {
        "hi": [round(v, 1) for v in hi],
        "lo": [round(v, 1) for v in lo],
        "rain": [int(round(v * d)) for v, d in zip(per_day, DAYS)],     # mm per day -> mm per month
    }


def validate(entry: dict) -> None:
    for k in ("hi", "lo", "rain"):
        v = entry.get(k)
        if not isinstance(v, list) or len(v) != 12 or not all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v):
            raise ValueError(f"{k} must be a list of 12 numbers")
    for i, (h, l) in enumerate(zip(entry["hi"], entry["lo"])):
        if l > h:
            raise ValueError(f"{MONTHS[i]}: low {l} is above high {h}")
        if not (-60 <= l and h <= 55):
            raise ValueError(f"{MONTHS[i]}: {l} to {h} C is outside what India can have")
    if not all(0 <= r <= 4000 for r in entry["rain"]):
        raise ValueError("a monthly rainfall is outside 0 to 4000 mm")


def sanity_problems(entries: dict) -> list[str]:
    """Anchor cities whose temperatures fall outside what anyone knows them to be."""
    out = []
    for cid, checks in ANCHORS.items():
        e = entries.get(cid)
        if not e or e.get("src") != "nasa-power":
            continue
        for key, label in (("hi", "high"), ("lo", "low")):
            for month, lo_ok, hi_ok in checks.get(key, []):
                v = e[key][month]
                if not (lo_ok <= v <= hi_ok):
                    out.append(f"{cid}: mean {label} in {MONTHS[month]} is {v} C, expected {lo_ok} to {hi_ok} C")
    return out


# ── Writing data/weather.js ───────────────────────────────────────────────────────────────────────────────────

def render(meta: dict, order: list[str], entries: dict) -> str:
    ids = [i for i in order if i in entries]
    lines = [HEADER.rstrip("\n"), "window.KYT_WEATHER = {", '  "meta": ' + json.dumps(meta, ensure_ascii=False) + ",", '  "cities": {']
    for n, cid in enumerate(ids):
        e = entries[cid]
        arr = lambda k: json.dumps(e[k], separators=(", ", ": "))
        lines.append(f'    {json.dumps(cid)}: {{"hi": {arr("hi")}, "lo": {arr("lo")}, "rain": {arr("rain")}, "src": {json.dumps(e["src"])}}}'
                     + ("," if n < len(ids) - 1 else ""))
    lines += ["  }", "};", ""]
    return "\n".join(lines)


def write_atomic(path: Path, text: str) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)


# ── The run ───────────────────────────────────────────────────────────────────────────────────────────────────

def run(args, fetch=None, sleep=time.sleep, today=None, out=print) -> int:
    fetch = fetch or (lambda url: fetch_json(url, retries=args.retries, timeout=args.timeout, sleep=sleep))
    today = today or datetime.date.today().isoformat()
    cities = load_cities(args.cities_file)
    order = [c["id"] for c in cities]
    by_id = {c["id"]: c for c in cities}
    existing = load_weather(args.weather_file)
    old = {k: v for k, v in existing["cities"].items() if k in by_id}
    overrides = load_overrides(args.overrides_file)
    names = (args.hi_param, args.lo_param, RAIN_PARAM)
    params_meta = {"hi": names[0], "lo": names[1], "rain": names[2]}
    params_changed = bool(old) and existing["meta"].get("params") != params_meta
    if params_changed:                                       # old numbers mean something else: never keep or mix them
        out("The temperature parameters changed since the last run, so every city is fetched again.")
        args.refresh, args.cities, args.limit = True, None, 0
    for cid in overrides:
        if cid not in by_id:
            out(f"warning: overrides has '{cid}', which is not a city in {args.cities_file.name}")

    wanted = None
    if args.cities:
        wanted = [c.strip() for c in args.cities.split(",") if c.strip()]
        unknown = [c for c in wanted if c not in by_id]
        if unknown:
            raise SystemExit("unknown city id: " + ", ".join(unknown))
    pool = [c for c in cities if wanted is None or c["id"] in wanted]
    if args.limit:
        pool = pool[: args.limit]
    pool_ids = {c["id"] for c in pool}

    args.cache_dir.mkdir(parents=True, exist_ok=True)
    entries, failed, fetched, cached, kept, from_override = {}, [], 0, 0, 0, 0
    todo = [c for c in cities if c["id"] in pool_ids]
    last_network = False

    for c in cities:
        cid = c["id"]
        ov = overrides.get(cid)
        if ov is not None:                                   # a hand correction always wins, nothing to fetch
            try:
                entry = {k: ov.get(k) for k in ("hi", "lo", "rain")}
                validate(entry)
                entries[cid] = {**entry, "src": "override"}
                from_override += 1
                continue
            except ValueError as e:
                out(f"warning: override for {cid} ignored ({e}); an override needs hi, lo and rain, 12 numbers each")
        have = old.get(cid)
        if have and have.get("src") == "nasa-power" and (cid not in pool_ids or not args.refresh):
            entries[cid] = have
            kept += 1
            continue
        if cid not in pool_ids:                              # outside this run's selection, and nothing to keep
            continue
        n = todo.index(c) + 1
        cache_file = args.cache_dir / f"{cid}.json"
        url = request_url(c["lat"], c["lng"], args.community, names)
        entry = None
        if cache_file.exists() and not args.refresh:         # a cached answer is used only if it still parses
            try:
                blob = json.loads(cache_file.read_text(encoding="utf-8"))
                if blob.get("url") == url:
                    entry = parse_response(blob["data"], names)
                    validate(entry)
                    cached += 1
            except (ValueError, KeyError):
                entry = None
        try:
            if entry is None:
                if last_network:
                    sleep(args.delay)
                raw = fetch(url)
                last_network = True
                fetched += 1
                entry = parse_response(raw, names)
                validate(entry)
                cache_file.write_text(json.dumps({"url": url, "fetched": today, "data": raw}), encoding="utf-8")
            entries[cid] = {**entry, "src": "nasa-power"}
            out(f"[{n}/{len(todo)}] {cid}: ok")
        except (RuntimeError, ValueError) as e:
            failed.append((cid, str(e)))
            out(f"[{n}/{len(todo)}] {cid}: FAILED, {e}")
            if cid in old and not params_changed:
                entries[cid] = old[cid]                      # keep what we had rather than lose the city
                # (but never across a parameter change: those numbers mean something else, so the city waits for the next run)

    changed = [cid for cid in order if cid in entries and old.get(cid) != entries[cid]]
    unchanged_set = set(entries) == set(existing["cities"]) and not changed   # also catches cities that left cities.js
    meta = {"source": SOURCE_NAME, "period": args.period, "units": {"hi": "C", "lo": "C", "rain": "mm per month"}, "params": params_meta,
            "generated": today}
    same_meta = {k: v for k, v in existing["meta"].items() if k != "generated"} == {k: v for k, v in meta.items() if k != "generated"}
    problems = [] if args.no_sanity_check else sanity_problems(entries)
    wrote = False
    if unchanged_set and same_meta:
        out("No changes: data/weather.js is already up to date.")
    elif problems:
        out("\nNOT WRITTEN: these temperatures look wrong, so the file was left alone:")
        out("\n".join("  " + p for p in problems))
        out("Likely a wrong parameter name or a changed API. If the numbers are right, run again with --no-sanity-check.")
    elif args.dry_run:
        out(f"Dry run: would write {len(entries)} cities ({len(changed)} new or changed).")
    else:
        write_atomic(args.weather_file, render(meta, order, entries))
        wrote = True

    refreshed_changes = []
    for cid in changed:
        if cid in old and cid in entries and entries[cid]["src"] == "nasa-power" and old[cid].get("src") == "nasa-power":
            d = max(max(abs(a - b) for a, b in zip(old[cid][k], entries[cid][k])) for k in ("hi", "lo"))
            if d >= 0.5:
                refreshed_changes.append((cid, d))
    out("")
    out(f"Cities: {len(entries)} of {len(cities)} have weather. Fetched {fetched}, from cache {cached}, kept {kept}, "
        f"hand-corrected {from_override}, failed {len(failed)}." + ("  (written)" if wrote else ""))
    if refreshed_changes:
        out("Temperatures moved by 0.5 C or more since the last run: " + ", ".join(f"{c} ({d:.1f})" for c, d in refreshed_changes))
    missing = [c["id"] for c in cities if c["id"] not in entries]
    if missing and (wanted is None and not args.limit):
        out(f"No weather yet for {len(missing)} cities: " + ", ".join(missing))
    hills = [cid for cid in order if cid in entries and by_id[cid].get("setting") == "hills" and entries[cid]["src"] == "nasa-power"]
    if hills:
        out(f"\nSpot-check these {len(hills)} hill cities against IMD normals; a 55 km grid smooths mountains. "
            "Correct any that look wrong in data/weather-overrides.json:\n  " + ", ".join(hills))
    if failed:
        out("\nFailed:")
        for cid, why in failed:
            out(f"  {cid}: {why}")
    return 1 if (failed or problems) else 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Update data/weather.js from NASA POWER climatology.",
                                formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    p.add_argument("--cities", help="comma-separated city ids to fetch (default: every city without weather)")
    p.add_argument("--refresh", action="store_true", help="fetch again even if a city already has weather (ignores the cache)")
    p.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    p.add_argument("--limit", type=int, default=0, help="only look at the first N cities, for a quick trial")
    p.add_argument("--delay", type=float, default=0.5, help="seconds to wait between requests")
    p.add_argument("--retries", type=int, default=4, help="retries per request for timeouts, 429 and 5xx")
    p.add_argument("--timeout", type=float, default=60, help="seconds before a request is given up on")
    p.add_argument("--community", default=COMMUNITY, help="NASA POWER community")
    p.add_argument("--hi-param", default=HI_PARAM, help="NASA parameter for the mean daily high")
    p.add_argument("--lo-param", default=LO_PARAM, help="NASA parameter for the mean daily low")
    p.add_argument("--no-sanity-check", action="store_true", help="write even if the anchor cities look wrong")
    p.add_argument("--period", default=DEFAULT_PERIOD, help="climatology years to record in the file's meta")
    p.add_argument("--cities-file", type=Path, default=ROOT / "data" / "cities.js")
    p.add_argument("--weather-file", type=Path, default=ROOT / "data" / "weather.js")
    p.add_argument("--overrides-file", type=Path, default=ROOT / "data" / "weather-overrides.json")
    p.add_argument("--cache-dir", type=Path, default=Path(__file__).resolve().parent / ".cache")
    return p


def main(argv=None) -> int:
    return run(build_parser().parse_args(argv))


if __name__ == "__main__":
    sys.exit(main())
